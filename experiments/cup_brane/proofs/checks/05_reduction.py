"""
Checks for Section 4 of proofs/05_main_sliding.md (the reduction lemma), for ARBITRARY words.

 (1) Lemma 4.1: for a slot a that is the first occurrence of its colour e, and every vertex K containing a,
         m_a(K) * m_a(K)^*  =  P * e_K,     P = prod over the strands y crossed by the strand of a:
              u_k x_a                      (y red, e = k)
              t_{e c(y)} x_a + t_{c(y) e} x_y   (y black, c(y) adjacent to e)
              1                             (otherwise),
     and P != 0.   (For a slot that is NOT a first occurrence the product lies in m A, where m is the
     ideal generated by the r_c: also checked.  So the argument of Lemma 4.2 is not available there.)
 (2) the component of the tree differential from K to K - a  is  +-m_a(K) + (terms with at least one pair),
     and every other term from a vertex containing a to K - a has at least one pair  (so it lies in m A,
     m = the ideal generated by the r_c).

    sage -python 05_reduction.py TYPE RANK N_WORDS MAXLEN [SEED]
"""
import sys, importlib, itertools, random
L = importlib.import_module("05_lib")

if __name__ == "__main__":
    ct = [sys.argv[1], int(sys.argv[2])]
    n_words, maxlen = int(sys.argv[3]), int(sys.argv[4])
    rng = random.Random(int(sys.argv[5]) if len(sys.argv) > 5 else 0)
    n1 = n0 = n2 = 0
    for _ in range(n_words):
        n = rng.randint(2, maxlen)
        w = tuple(rng.randint(1, ct[1]) for _ in range(n))
        red = rng.randint(1, ct[1])
        S = L.Setup(ct, red, w)
        for h in range(1, n + 1):
            for K in itertools.combinations(range(1, n + 1), h):
                K = frozenset(K)
                ids = L.strand_ids(S, K)
                terms = S.terms(K)
                for a in K:
                    e = w[a - 1]
                    first = e not in w[:a - 1]
                    (ta,) = [t for t in terms if t.j == a and not t.F]
                    # (2)
                    for t in terms:
                        if t.J == K - {a} and t is not ta:
                            assert t.F
                    n2 += 1
                    wa = L.word_of(S, S.beta(K, ta.J, ta.sigma))
                    p = ids.index(a)
                    assert wa == tuple(range(p, p - len(wa), -1))          # the unique reduced word
                    lhs = S.from_word(K, wa + tuple(reversed(wa)))
                    if not first:
                        # every coefficient is divisible by some r_c: the product vanishes modulo m
                        for braid, coeff in lhs:
                            for mon in coeff.monomials():
                                assert any(str(v).startswith("r_") for v in mon.variables())
                        n0 += 1
                        continue
                    P = S.K.idempotent(S.state(K))
                    for (y, x) in L.crossings(ids, wa)[0]:
                        assert x == a
                        if y == "W":
                            if e == red:
                                P = P * (S.mono((("u_%d" % e, 1),)) * L.dot(S, K, a))
                        elif S.st.adjacent(y, a):
                            cy = w[y - 1]
                            P = P * (S.mono((("t_%d_%d" % (e, cy), 1),)) * L.dot(S, K, a)
                                     + S.mono((("t_%d_%d" % (cy, e), 1),)) * L.dot(S, K, y))
                    assert lhs == P and not P.is_zero()
                    n1 += 1
    print("reduction lemma inputs, type %s, %d words: m_a m_a^* = P != 0 in %d cases (a first occurrence), "
          "= 0 mod m in %d cases (a not a first occurrence); structure of the mover-a block checked in %d cases"
          % (ct, n_words, n1, n0, n2))
